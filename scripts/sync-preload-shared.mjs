import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const projectRoot = join(__dirname, "..");
const preloadPath = join(projectRoot, "electron", "preload.cjs");
const require = createRequire(import.meta.url);
const { IPC_CHANNELS } = require(join(projectRoot, "electron", "ipc-channels.cjs"));
const { SETTINGS_DIRNAME } = require(join(projectRoot, "electron", "settings-constants.cjs"));
const { quickKeyBindings } = require(join(projectRoot, "electron", "quick-key-bindings.cjs"));

const START_MARKER = "// @generated-start shared-constants";
const END_MARKER = "// @generated-end shared-constants";

const stringifyJsValue = (value) => JSON.stringify(value, null, 2);

const buildGeneratedBlock = () => [
  START_MARKER,
  "// This block is auto-generated by scripts/sync-preload-shared.mjs.",
  "// Do not edit manually.",
  `const IPC_CHANNELS = Object.freeze(${stringifyJsValue(IPC_CHANNELS)});`,
  "",
  `const SETTINGS_DIRNAME = ${stringifyJsValue(SETTINGS_DIRNAME)};`,
  `const quickKeyBindings = Object.freeze(${stringifyJsValue(quickKeyBindings)});`,
  END_MARKER
].join("\n");

const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const replaceGeneratedBlock = (source, block) => {
  const pattern = new RegExp(
    `${escapeRegExp(START_MARKER)}[\\s\\S]*?${escapeRegExp(END_MARKER)}`,
    "m"
  );

  if (!pattern.test(source)) {
    throw new Error("Missing generated block markers in electron/preload.cjs.");
  }

  return source.replace(pattern, block);
};

const run = async () => {
  const current = await readFile(preloadPath, "utf-8");
  const next = replaceGeneratedBlock(current, buildGeneratedBlock());
  if (next === current) {
    return;
  }

  await writeFile(preloadPath, next, "utf-8");
};

run().catch((error) => {
  console.error(error instanceof Error ? error.message : "Failed to sync preload shared constants.");
  process.exitCode = 1;
});
